export function placeFor(regionCode: string, sigungu?: string): Place | null {
  const region = regionByCode(regionCode);
  if (!region) return null;
  const c = (sigungu && SIGUNGU_CENTER[regionCode]?.[sigungu]) || SIDO_CENTER[regionCode];
  if (!c) return null;
  return { label: sigungu ? `${region.label} ${sigungu}` : region.label, lat: c[0], lng: c[1] };
}

/**
 * "서울 강서구" — 시도 라벨 + 주소의 시군구 어절.
 * 주소의 두 번째 어절이 언제나 시군구는 아니다. SH 공고는 "서울특별시 일원(단지별 소재지 상이)"처럼 와서
 * 그대로 쓰면 "서울 일원(단지별"이 된다. 시·군·구로 끝나는 어절만 쓴다.
 * 앱(remote.ts)·번들(app-data.ts)·수집기(enrich-announcement.ts) 세 곳이 각자 들고 있던 규칙이다 (2026-09-24 감사).
 */
export function regionNameOf(regionCode: string, address?: string, fallbackSido?: string): string {
  const sido = regionByCode(regionCode)?.label ?? fallbackSido ?? regionCode;
  const token = address?.split(/s+/)[1];
  return token && /[시군구]$/.test(token) ? `${sido} ${token}` : sido;
}

/** "서울 마포구" 라벨 → 시도 코드·시군구 (프로필 workplace.label 역파싱) */
export function parsePlaceLabel(label: string | undefined): { regionCode: string; sigungu?: string } | null {
  if (!label) return null;
  const [sido, ...rest] = label.split(" ");
  const region = REGION_LIST.find((r) => r.label === sido);
  if (!region) return null;
  return { regionCode: region.code, sigungu: rest.length ? rest.join(" ") : undefined };
}

/**
 * 지금 공고를 모으고 있는 시도.
 *
 * 수집기는 `COLLECT_REGIONS` 환경변수로 이 범위를 정하고, 앱은 화면에 고지할 때 쓴다.
 * 두 곳이 갈리면 앱이 "서울·경기만 제공해요"라고 적어 놓고 다른 지역 공고를 보여 주게 된다.
 * 그래서 기본값을 여기 한 곳에 두고 수집기 기본값도 이 값을 쓴다.
 *
 * 넓힐 때 고치는 곳: 이 배열 하나. 화면 문구는 SERVICE_REGION_LABEL에서 만들어진다.
 */
// 수도권 셋 (2026-09-24 인천 추가). 엔진의 regionGuard도 11·28·41을 한 생활권으로 묶는다
export const SERVICE_REGIONS = ["11", "28", "41"] as const;

/** 고지에 쓰는 이름 ("서울·인천·경기"). 코드 목록이 바뀌면 문구도 따라 바뀐다 */
export const SERVICE_REGION_LABEL: string = SERVICE_REGIONS.map((c) => regionByCode(c)?.label ?? c).join("·");

/** 이 시도의 공고를 모으고 있는가. 코드가 없으면(입력 전) 판단하지 않고 true */
export const isServiceRegion = (regionCode: string | undefined): boolean =>
  regionCode === undefined || (SERVICE_REGIONS as readonly string[]).includes(regionCode);

/**
 * 같은 시도의 다른 코드. 2023~2024년 특별자치도 출범으로 법정동 코드가 바뀌었다 — 강원 42→51, 전북 45→52.
 * 우리 표준은 옛 코드(REGIONS)인데, 추출(LLM)은 새 코드를 내기도 한다. 군산 영구임대의 "군산시 거주"가
 * ["52"]로 추출돼, 군산 사람(45)도 거주 요건에서 떨어졌다(2026-09-23 감사). 비교할 때는 둘을 같은 곳으로 본다.
 */
export const REGION_ALIASES: Record<string, string[]> = { "42": ["51"], "51": ["42"], "45": ["52"], "52": ["45"] };

/** 이 시도 코드와 같은 곳을 가리키는 코드 전부 (자기 자신 포함) */
export const regionCodesOf = (code: string): string[] => [code, ...(REGION_ALIASES[code] ?? [])];
